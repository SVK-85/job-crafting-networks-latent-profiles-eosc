## 0.1 Define and create the workflow storage directories
#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
# 0.1.1 Define the project and results directories
# 0.1.1.1 Project
project_root_dir <- getwd()
# 0.1.1.2 Directories
results_root_dir <- file.path(project_root_dir, "Results_Job_Crafting")

# 0.1.2 Define the directory labels for Steps 00-14
step_dir_labels <- c("00" = "Computational_Environment",
                     "01" = "Data_Import_and_Provenance",
                     "02" = "Variable_Registry_and_Codebook",
                     "03" = "Data_Cleaning_and_Descriptives",
                     "04" = "Missing_Data_Diagnostics",
                     "05" = "JCQ_CFA",
                     "06" = "JCS_CFA",
                     "07" = "UWES_CFA_and_Mokken",
                     "08" = "JCS_JCQ_CFA",
                     "09" = "JCS_JCQ_LNM",
                     "10" = "Scores_and_Reliability",
                     "11" = "Zero_Order_Pearson_Correlations",
                     "12" = "LPA_and_Auxiliary_Analyses",
                     "13" = "Joint_GGM_on_JC_WAMI_UWES",
                     "14" = "Joint_GGM_Bootstrap_and_Stability",
                     "15" = "Joint_GGM_Bridge_Nodes")

# 0.1.3 Create the directories and assign their output_dir_XX objects
for (step in names(step_dir_labels)) {
# 0.1.3.1 Build the output path for the current workflow step
output_path <- file.path(results_root_dir, paste0("Step", step, "_", 
                                                  step_dir_labels[[step]]))
# 0.1.3.2 Create the step directory and any missing parent directories
dir.create(output_path, recursive = TRUE, showWarnings = FALSE)
# 0.1.3.3 Verify that the step directory exists
stopifnot(dir.exists(output_path))
# 0.1.3.4 Assign the step-specific output directory object
assign(paste0("output_dir_", step), output_path)
}

# 0.1.4 Report the results directory
message("Results directory: ", results_root_dir)

#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
## 0.2 Install the required packages
#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
# 0.2.1 Define the packages required by the workflow
required_packages_global <- c("lavaan", "psychonetrics", "qgraph", "semPlot",
"networktools", "bootnet", "huge", "mgm", "mclust", "mix", "tidyLPA", "LCPA",
"emmeans", "GPArotation", "misty", "mvnmle", "mokken", "psych", "haven",
"dplyr", "tidyr", "readr", "tibble", "ggplot2", "ggridges", "ggpattern",
"scales", "writexl")

# 0.2.2 Configure the personal library and installation settings
user_library_dir <- path.expand(Sys.getenv("R_LIBS_USER"))
# 0.2.2.1 Create the personal library directory if needed
dir.create(user_library_dir, recursive = TRUE, showWarnings = FALSE)
# 0.2.2.2 Verify that the personal library exists and is writable
stopifnot(dir.exists(user_library_dir), file.access(user_library_dir, 2) == 0)
# 0.2.2.3 Prepend the personal library to the package search paths
.libPaths(c(user_library_dir, .libPaths()))
# 0.2.2.4 Configure CRAN, the download timeout, and parallel installation
options(repos = c(CRAN = "https://cloud.r-project.org"),
        timeout = max(600, getOption("timeout")), Ncpus = 2L)

# 0.2.3 Identify missing packages before loading any analysis namespaces
installed_packages_global <- rownames(utils::installed.packages())
# 0.2.4 Select required packages that are not installed
missing_packages_global <- setdiff(required_packages_global,
                                   installed_packages_global)

# 0.2.5 Install pak and resolve R packages and Ubuntu system requirements
# 0.2.5.1 Run installation only when required packages are missing
if (length(missing_packages_global) > 0L) {
# 0.2.5.2 Check whether pak is available before installing it
if (!requireNamespace("pak", quietly = TRUE)) {
# 0.2.5.3 Select the pak repository for the current platform and architecture
pak_repository <- sprintf("https://r-lib.github.io/p/pak/stable/%s/%s/%s",
                          .Platform$pkgType, 
                          R.Version()$os, 
                          R.Version()$arch)
# 0.2.5.4 Install pak in the personal library
utils::install.packages("pak", lib = user_library_dir, 
                               repos = pak_repository)
}
if (!requireNamespace("pak", quietly = TRUE)) {
stop("pak installation failed; inspect the bootstrap log.")
}
# 0.2.5.5 Enable system requirement installation and verbose reporting
options(pkg.sysreqs = TRUE, 
        pkg.sysreqs_verbose = TRUE)
# 0.2.5.6 Report the names of the missing packages
message("Installing missing packages: ",
        paste(missing_packages_global, 
              collapse = ", "))
# 0.2.5.7 Install missing packages and dependencies without requesting upgrades
pak::pkg_install(missing_packages_global, 
                 lib = .libPaths(),
                 dependencies = NA, 
                 upgrade = FALSE, 
                 ask = FALSE)
}

# 0.2.5 Verify package loading before continuing to the analysis environment
remaining_packages_global <- required_packages_global[
!vapply(required_packages_global, 
        requireNamespace, 
        logical(1), 
        quietly = FALSE)
]
if (length(remaining_packages_global) > 0L) {
stop("Required packages cannot be loaded: ",
     paste(remaining_packages_global, 
           collapse = ", "),
     ". Inspect the first error in the bootstrap log.")
}
message("All required R packages are available.")

#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
## 0.3 Load the analysis packages 
#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
# 0.3.1 Attach SEM and network-analysis packages
library(lavaan)                 # Confirmatory factor analysis & SEM
library(psychonetrics)          # Latent network estimation & model comparison
library(qgraph)                 # Network plots & centrality indices
library(semPlot)                # CFA path diagrams & LISREL representations
library(networktools)           # Expected influence & bridge indices
library(bootnet)                # Network bootstrap accuracy & stability
library(huge)                   # Nonparanormal score transformations
library(mgm)                    # Mixed graphical models & predictability

# 0.3.2 Attach profile-analysis & auxiliary-comparison packages
library(mclust)                 # Estimation backend selected by tidyLPA
library(mix)                    # Required by mclust::imputeData()
library(tidyLPA)                # Profile estimation, comparison & plotting
library(LCPA)                   # BCH outcome & demographic comparisons
library(emmeans)                # Contrasts from imported estimates & covariance

# 0.3.3 Attach psychometric & missing-data analysis packages
library(GPArotation)            # Rotation backend used by psych::omega()
library(misty)                  # Missingness, frequencies, Little's MCAR test
library(mvnmle)                 # Estimation backend for misty::na.test()
library(mokken)                 # Mokken scalability coefficients
library(psych)                  # Reliability, descriptives & scoring

# 0.3.4 Attach data-import & data-management packages
library(haven)                  # SPSS data import with label preservation
library(dplyr)                  # Data manipulation & the %>% pipe
library(tidyr)                  # Reshaping & missing-value replacement
library(readr)                  # CSV & text-file export
library(tibble)                 # Conversion of row names to an explicit column

# 0.3.5 Attach statistical visualization packages
library(ggplot2)                # Statistical graphics & figure export
library(ggridges)               # Raw & transformed score distributions
library(ggpattern)              # Patterned bars for profile figures
library(scales)                 # Percentage labels for tables & figures

# 0.3.6 Attach spreadsheet-export packages
library(writexl)                # Single-sheet Excel workbook export

#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
## 0.4 Record the computational environment and package versions
#-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=#
# 0.4.1 Record the computational environment after package loading
# 0.4.1.1 UTC timestamp
computational_environment <- list(recorded_utc = format(Sys.time(),
                                  "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
                                   project_root = project_root_dir, 
                                   results_root = results_root_dir,
                                   system = Sys.info(), 
                                   locale = Sys.getlocale(), 
                                   timezone = Sys.timezone(),
                                   rng_kind = RNGkind(), 
                                   repositories = getOption("repos"),
                                   library_paths = .libPaths(), 
                                   session = utils::sessionInfo())

# 0.4.2 Save the environment and display its TXT report
saveRDS(computational_environment, 
        file.path(output_dir_00,"1.Step00_Computational_Environment.rds"))
# 0.4.2.1 Capture the environment report and save it as a TXT file
environment_report <- utils::capture.output(print(computational_environment))
writeLines(environment_report, file.path(output_dir_00,
"2.Step00_Computational_Environment.txt"), useBytes = TRUE)
# 0.4.2.2 Display the same environment report in the console
writeLines(environment_report)

# 0.4.3 Record package versions in the same order as Step 0.3
package_versions_global <- data.frame(package = required_packages_global,
                                      version = vapply(required_packages_global, 
                                      function(x)
as.character(utils::packageVersion(x)), character(1)), row.names = NULL)

# 0.4.4 Save the package report in Step 00 and display it in the console
package_versions_report <- utils::capture.output(print(package_versions_global,
                                                       row.names = FALSE, 
                                                       right = FALSE))
 # 0.4.4.1 Save the package version report as a TXT file                                                   
writeLines(package_versions_report, file.path(output_dir_00,
                                              "3.Step00_Package_Versions.txt"), 
           useBytes = TRUE)
# 0.4.4.1 Display the package version report in the console   
writeLines(package_versions_report)

# 0.4.5 Archive all installed R package versions, including dependencies
installed_package_inventory <- as.data.frame(utils::installed.packages()[,
                                             c("Package", 
                                             "Version", 
                                             "LibPath", 
                                             "Built"), 
                                             drop = FALSE], 
                                             row.names = NULL)
# 0.4.5.1 Save the installed package inventory as a CSV file                                            
utils::write.csv(installed_package_inventory, 
                 file.path(output_dir_00, "4.Step00_Installed_Packages.csv"), 
                 row.names = FALSE)
